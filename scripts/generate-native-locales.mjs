#!/usr/bin/env node
// Native strings and store listings from the TypeScript catalogue
// (src/i18n/locales/*.ts). The catalogue is the only place to edit copy.
//
//   node scripts/generate-native-locales.mjs          write every file
//   node scripts/generate-native-locales.mjs --check  fail if anything is stale
//
// Writes:
//  - Android: app + plugin values-*/strings.xml, res/xml/locales_config.xml
//  - iOS: <lang>.lproj/InfoPlist.strings + Localizable.strings, Info.plist
//    CFBundleLocalizations, and the Xcode project's variant groups
//  - Store listings: store/fastlane/metadata/{android,ios}/<locale>/*.txt
// Both stores detect the app's languages from these files.
import './lib/cli-failure.mjs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { LANGUAGES } from '../src/i18n/languages.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const GENERATED = 'Generated by scripts/generate-native-locales.mjs from src/i18n/locales. Do not edit.'

const appRes = join(root, 'android/app/src/main/res')
const pluginRes = join(root, 'plugins/remote-ring/android/src/main/res')
const iosApp = join(root, 'ios/App/App')
const pbxprojPath = join(root, 'ios/App/App.xcodeproj/project.pbxproj')
const infoPlistPath = join(iosApp, 'Info.plist')
const storeDir = join(root, 'store/fastlane/metadata')

/** Android resource name → catalogue key (native section), plugin module. */
const PLUGIN_STRINGS = {
  remote_ring_channel_active: 'channelActive',
  remote_ring_channel_active_description: 'channelActiveDescription',
  remote_ring_channel_fallback: 'channelFallback',
  remote_ring_channel_fallback_description: 'channelFallbackDescription',
  remote_ring_notification_title: 'ringingTitle',
  remote_ring_notification_text: 'ringingBody',
  remote_ring_notification_text_from: 'ringingFrom',
  remote_ring_stop: 'stop',
  remote_ring_privacy_footer: 'privacyFooter',
  remote_ring_channel_health: 'healthChannel',
  remote_ring_channel_health_description: 'healthChannelDescription',
  remote_ring_health_title: 'healthTitle',
  remote_ring_health_text: 'healthText',
  remote_ring_listener_label: 'appName',
}

/** Localizable.strings: the English text is the key, as Swift literals use it. */
const IOS_STRINGS = [
  'ringingTitle',
  'ringingBody',
  'ringingFrom',
  'stopHint',
  'intentRingTitle',
  'intentRingDescription',
  'intentMessage',
  'intentMessageDescription',
  'intentSender',
  'intentSenderDescription',
  'intentStopTitle',
  'intentStopDescription',
]

/** Store limits (characters). */
const LIMITS = { title: 30, shortDescription: 80, subtitle: 30, keywords: 100, promo: 170, description: 4000 }

async function loadCatalogue(code) {
  const mod = await import(pathToFileURL(join(root, 'src/i18n/locales', `${code}.ts`)).href)
  return mod.default
}

const xml = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/^([@?])/, '\\$1')
const strings = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')
const android = (s) => s.replace(/\{\w+\}/g, '%1$s')
const ios = (s) => s.replace(/\{\w+\}/g, '%@')

const pending = []
let stale = 0

async function emit(path, content) {
  let current = null
  try {
    current = await readFile(path, 'utf8')
  } catch {
    current = null
  }
  if (current === content) return
  if (check) {
    stale++
    console.error(`stale: ${path.replace(root, '.')}`)
    return
  }
  pending.push(mkdir(dirname(path), { recursive: true }).then(() => writeFile(path, content)))
}

function stringsXml(entries) {
  const body = entries.map(([name, value]) => `    <string name="${name}">${xml(value)}</string>`).join('\n')
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${GENERATED} -->\n<resources>\n${body}\n</resources>\n`
}

function dotStrings(entries) {
  return `/* ${GENERATED} */\n${entries.map(([k, v]) => `"${strings(k)}" = "${strings(v)}";`).join('\n')}\n`
}

const en = await loadCatalogue('en')
const problems = []

for (const lang of LANGUAGES) {
  const m = await loadCatalogue(lang.code)
  const suffix = lang.android ? `-${lang.android}` : ''

  // ---- Android ----
  const appEntries = [
    ['app_name', m.native.appName],
    ['title_activity_main', m.native.appName],
  ]
  if (!lang.android) appEntries.push(['package_name', 'app.smsring'], ['custom_url_scheme', 'app.smsring'])
  await emit(join(appRes, `values${suffix}`, 'strings.xml'), stringsXml(appEntries))
  await emit(
    join(pluginRes, `values${suffix}`, 'strings.xml'),
    stringsXml(Object.entries(PLUGIN_STRINGS).map(([name, key]) => [name, android(m.native[key])])),
  )

  // ---- iOS ----
  const lproj = join(iosApp, `${lang.ios}.lproj`)
  await emit(join(lproj, 'InfoPlist.strings'), dotStrings([['CFBundleDisplayName', m.native.appName]]))
  await emit(join(lproj, 'Localizable.strings'), dotStrings(IOS_STRINGS.map((k) => [ios(en.native[k]), ios(m.native[k])])))

  // ---- Store listings ----
  const s = m.store
  for (const [key, limit] of Object.entries(LIMITS)) {
    const len = [...s[key]].length
    if (len > limit) problems.push(`${lang.code}: store.${key} is ${len} > ${limit}`)
  }
  const play = join(storeDir, 'android', lang.play)
  await emit(join(play, 'title.txt'), `${s.title}\n`)
  await emit(join(play, 'short_description.txt'), `${s.shortDescription}\n`)
  await emit(join(play, 'full_description.txt'), `${s.description}\n`)
  const apple = join(storeDir, 'ios', lang.appStore)
  await emit(join(apple, 'name.txt'), `${s.title}\n`)
  await emit(join(apple, 'subtitle.txt'), `${s.subtitle}\n`)
  await emit(join(apple, 'description.txt'), `${s.description}\n`)
  await emit(join(apple, 'keywords.txt'), `${s.keywords}\n`)
  await emit(join(apple, 'promotional_text.txt'), `${s.promo}\n`)
}

// ---- Android per-app language list ----
await emit(
  join(appRes, 'xml', 'locales_config.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${GENERATED} -->\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n${LANGUAGES.map(
    (l) => `    <locale android:name="${l.bcp47}" />`,
  ).join('\n')}\n</locale-config>\n`,
)

// ---- iOS Info.plist ----
{
  const plist = await readFile(infoPlistPath, 'utf8')
  const list = LANGUAGES.map((l) => `\t\t<string>${l.ios}</string>`).join('\n')
  const next = plist.replace(
    /(<key>CFBundleLocalizations<\/key>\s*<array>)[\s\S]*?(\s*<\/array>)/,
    `$1\n${list}$2`,
  )
  await emit(infoPlistPath, next)
}

// ---- Xcode project: variant groups for the .strings files ----
{
  let pbx = await readFile(pbxprojPath, 'utf8')
  // Drop what a previous run generated (ids prefixed D7), then add it back.
  // Whole variant-group blocks first, then single lines.
  pbx = pbx.replace(/\t\tD7[0-9A-F]{22} \/\* [\w.]+ \*\/ = \{\n\t\t\tisa = PBXVariantGroup;[\s\S]*?\n\t\t\};\n/g, '')
  pbx = pbx.replace(/^\t\tD7[0-9A-F]{22} .*\n/gm, '')
  pbx = pbx.replace(/^\t\t\t\tD7[0-9A-F]{22} .*,\n/gm, '')

  const id = (kind, n) => `D7${kind}${String(n).padStart(2, '0')}`.padEnd(24, '0')
  const files = ['InfoPlist.strings', 'Localizable.strings']
  const refs = []
  const groups = []
  const buildFiles = []
  files.forEach((file, f) => {
    const group = id(`${f}9`, 0)
    const build = id(`${f}8`, 0)
    const children = LANGUAGES.map((l, i) => {
      const ref = id(`${f}0`, i)
      const name = /^[\w]+$/.test(l.ios) ? l.ios : `"${l.ios}"`
      refs.push(`\t\t${ref} /* ${l.ios} */ = {isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = ${name}; path = "${l.ios}.lproj/${file}"; sourceTree = "<group>"; };\n`)
      return `\t\t\t\t${ref} /* ${l.ios} */,`
    })
    groups.push(`\t\t${group} /* ${file} */ = {\n\t\t\tisa = PBXVariantGroup;\n\t\t\tchildren = (\n${children.join('\n')}\n\t\t\t);\n\t\t\tname = ${file};\n\t\t\tsourceTree = "<group>";\n\t\t};\n`)
    buildFiles.push({ build, group, file })
  })

  pbx = pbx.replace('/* End PBXFileReference section */', `${refs.join('')}/* End PBXFileReference section */`)
  pbx = pbx.replace('/* End PBXVariantGroup section */', `${groups.join('')}/* End PBXVariantGroup section */`)
  pbx = pbx.replace(
    '/* End PBXBuildFile section */',
    `${buildFiles.map((b) => `\t\t${b.build} /* ${b.file} in Resources */ = {isa = PBXBuildFile; fileRef = ${b.group} /* ${b.file} */; };\n`).join('')}/* End PBXBuildFile section */`,
  )
  // App group children and Resources build phase.
  pbx = pbx.replace(
    /(504EC3061FED79650016851F \/\* App \*\/ = \{\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = \(\n)/,
    `$1${buildFiles.map((b) => `\t\t\t\t${b.group} /* ${b.file} */,\n`).join('')}`,
  )
  pbx = pbx.replace(
    /(504EC3021FED79650016851F \/\* Resources \*\/ = \{\n\t\t\tisa = PBXResourcesBuildPhase;\n\t\t\tbuildActionMask = \d+;\n\t\t\tfiles = \(\n)/,
    `$1${buildFiles.map((b) => `\t\t\t\t${b.build} /* ${b.file} in Resources */,\n`).join('')}`,
  )
  pbx = pbx.replace(
    /knownRegions = \([\s\S]*?\);/,
    `knownRegions = (\n${['Base', ...LANGUAGES.map((l) => l.ios)].map((r) => `\t\t\t\t${/^[\w]+$/.test(r) ? r : `"${r}"`},`).join('\n')}\n\t\t\t);`,
  )
  await emit(pbxprojPath, pbx)
}

await Promise.all(pending)

if (problems.length) {
  console.error(problems.join('\n'))
  process.exit(1)
}
if (check && stale) {
  console.error(`${stale} generated file(s) out of date: run npm run locales`)
  process.exit(1)
}
console.log(check ? 'Native locales are up to date.' : `Native locales written for ${LANGUAGES.length} languages.`)

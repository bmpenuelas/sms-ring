/** Russian plural: 1 (not 11) → one, 2–4 (not 12–14) → few, else many. */
const ru3 = (n: number, one: string, few: string, many: string) => {
  const d = n % 10
  const t = n % 100
  if (d === 1 && t !== 11) return one
  return d >= 2 && d <= 4 && (t < 12 || t > 14) ? few : many
}

